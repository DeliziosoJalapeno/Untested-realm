"""Re-sync faq_dump.md from the official card FAQ (sorcerytcg.com/codex).

Every codex page streams the WHOLE codex and FAQ in its Next.js RSC payload, so one page is enough.
Each FAQ entry is written once per card it covers, cards in alphabetical order, entries in the site's order.
Then run `npm run gen:faq` to rebuild faqData.json from it.
Usage: python scripts/sync_faq.py [out=faq_dump.md] [saved-page.html]
"""
import json
import os
import re
import sys
import unicodedata
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CARDS = os.path.join(ROOT, 'packages', 'shared', 'src', 'cards', 'cards.json')
CODEX_PAGE = 'https://sorcerytcg.com/codex/changelog'
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'faq_dump.md')
if len(sys.argv) > 2:
    html = open(sys.argv[2], encoding='utf-8').read()
else:
    req = urllib.request.Request(CODEX_PAGE, headers={'User-Agent': 'Mozilla/5.0'})
    html = urllib.request.urlopen(req, timeout=60).read().decode('utf-8')

# the page streams its data as self.__next_f.push([1,"<json string>"]) chunks
chunks = re.findall(r'self\.__next_f\.push\(\[1,("(?:[^"\\]|\\.)*")\]\)', html)
payload = ''.join(json.loads(c) for c in chunks)


def faq_docs(payload: str):
    """every FAQ document in the payload ({"_createdAt":…,"_type":"faq",…}), decoded whole with
    raw_decode. Each document is streamed more than once; dedupe by _id."""
    dec = json.JSONDecoder()
    seen = set()
    for m in re.finditer(re.escape('{"_createdAt"'), payload):
        try:
            obj, _ = dec.raw_decode(payload, m.start())
        except ValueError:
            continue
        if isinstance(obj, dict) and obj.get('_type') == 'faq' and obj.get('_id') not in seen:
            seen.add(obj.get('_id'))
            yield obj


def block_text(block) -> str:
    """Portable Text block → one line (list items keep a "- " marker)"""
    if not isinstance(block, dict) or block.get('_type') != 'block':
        return ''
    text = ''.join(ch.get('text', '') for ch in block.get('children', []) if isinstance(ch, dict))
    if block.get('listItem'):
        return '  ' * (max(1, block.get('level', 1)) - 1) + '- ' + text
    return text


def blocks_text(blocks) -> str:
    # single newlines only: gen_faq.ts ends an answer at a blank line
    return '\n'.join(t for t in (block_text(b) for b in blocks or []) if t.strip()).strip()


def slug(name: str) -> str:
    name = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode().replace("'", '')
    return re.sub(r'[^a-z0-9]+', '_', name.lower()).strip('_')


with open(CARDS, encoding='utf-8') as f:
    card_by_slug = {slug(c['name']): c['name'] for c in json.load(f)}

by_card: dict[str, list] = {}
unknown = set()
for doc in faq_docs(payload):
    q, a = blocks_text(doc.get('question')), blocks_text(doc.get('answer'))
    if not q or not a:
        continue
    for s in doc.get('cards') or []:
        name = card_by_slug.get(s)
        if not name:
            unknown.add(s)
            continue
        by_card.setdefault(name, []).append((doc.get('orderRank') or '', q, a))

with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Sorcery: Contested Realm — card FAQ (verbatim from sorcerytcg.com/codex)\n')
    f.write('# Generated by scripts/sync_faq.py from the official codex FAQ data; do not hand-write paraphrases — re-sync instead.\n\n')
    for name in sorted(by_card, key=str.lower):
        for _, q, a in sorted(by_card[name], key=lambda e: e[0]):
            f.write(f'### {name}\nQ: {q}\nA: {a}\n\n')
print(sum(len(v) for v in by_card.values()), 'entries for', len(by_card), 'cards')
if unknown:
    print('FAQ card slugs not in cards.json:', ', '.join(sorted(unknown)))
